// TestFloat256_SinCosAccuracy checks that the error of Sin, Cos, and Sincos is less than 1 ulp,
// and that almost all results are correctly rounded.
// The test data is generated by scripts/gen_sin_testdata.py.
func TestFloat256_SinCosAccuracy(t *testing.T) {
	f, err := os.Open("testdata/sin256.txt")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()

	parse := func(s string) Float256 {
		var x Float256
		for i := range x {
			v, err := strconv.ParseUint(s[16*i:16*(i+1)], 16, 64)
			if err != nil {
				t.Fatal(err)
			}
			x[i] = v
		}
		return x
	}
	within1ulp := func(got, want Float256) bool {
		inf := NewFloat256Inf(1)
		return eq256(got, want) || eq256(got, want.Nextafter(inf)) || eq256(got, want.Nextafter(inf.Neg()))
	}

	var total, misrounded int
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		x, wantSin, wantCos := parse(fields[0]), parse(fields[1]), parse(fields[2])

		sin, cos := x.Sincos()
		total += 2
		if !eq256(sin, wantSin) {
			misrounded++
		}
		if !eq256(cos, wantCos) {
			misrounded++
		}
		if !within1ulp(sin, wantSin) {
			t.Errorf("Sincos(%v) sin = %v; want %v", x, sin, wantSin)
		}
		if !within1ulp(cos, wantCos) {
			t.Errorf("Sincos(%v) cos = %v; want %v", x, cos, wantCos)
		}
		if got := x.Sin(); !eq256(got, sin) {
			t.Errorf("Sin(%v) = %v; want %v", x, got, sin)
		}
		if got := x.Cos(); !eq256(got, cos) {
			t.Errorf("Cos(%v) = %v; want %v", x, got, cos)
		}
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}

	// The error bound is about 0.6 ulp,
	// so the result may be misrounded if the exact value is close to a midpoint.
	if misrounded*100 > total {
		t.Errorf("%d of %d results are not correctly rounded; want at most 1%%", misrounded, total)
	}
}
