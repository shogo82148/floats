package floats

import (
	"math"
	"testing"
)

func TestFloat128_J0(t *testing.T) {
	tests := []struct {
		x    Float128
		want string
	}{
		{exact128(0.001), "0.9999997500000156249995555638894490878922808529534484185615"},
		{exact128(0.5), "0.9384698072408129042284046735997126255689267970968215765547"},
		{exact128(1), "0.7651976865579665514497175261026632209092742897553252418615"},
		{exact128(-1), "0.7651976865579665514497175261026632209092742897553252418615"},
		{exact128(2), "0.2238907791412356680518274546499486258251544822186076031284"},
		{exact128(5), "-0.1775967713143383043473970130747587110711303560085091289907"},
		{exact128(10), "-0.2459357644513483351977608624853287538296000728265665696992"},
		{exact128(50), "0.05581232766925181500475047852943396817659267104557813619661"},
		{exact128(100), "0.01998585030422312242422839095084899068063357885902792955864"},
		{exact128(300), "-0.03329855487630566800748309439984550659781158351287717945289"},

		// straddling the Miller / asymptotic crossover (500)
		{exact128(499), "-0.009593099634978921257277451132699062703691475365590130742150"},
		{exact128(499.9), "-0.03288456342784675855449053232646672165014714582968061039151"},
		{exact128(500), "-0.03410055688073199826512506045189455813144279153168387048260"},
		{exact128(500.1), "-0.03497561973464262440191454809235197505285591005202369151513"},
		{exact128(501), "-0.02723846374763358467304325210953171020318360114254779904130"},

		{exact128(1000), "0.02478668615242017456133073111569370878616644713324654841481"},
		{exact128(5000), "-0.006648984251448347893586884896846940288281804283918913746490"},
		{exact128(50000), "-0.002567842177833239901843726994952437565328219447306741696311"},
	}

	for _, tt := range tests {
		got := tt.x.J0()
		if !close128(got, tt.want) {
			t.Errorf("J0(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}

	strictTests := []struct {
		x    Float128
		want Float128
	}{
		{exact128(0), exact128(1)},
		{exact128(math.Copysign(0, -1)), exact128(1)},
		{exact128(math.Inf(1)), exact128(0)},
		{exact128(math.Inf(-1)), exact128(0)},
		{exact128(math.NaN()), exact128(math.NaN())},
	}

	for _, tt := range strictTests {
		got := tt.x.J0()
		if !eq128(got, tt.want) {
			t.Errorf("J0(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}
}
