func TestFloat128_Asinh(t *testing.T) {
	t.Parallel()
	tests := []struct {
		x    Float128
		want string
	}{
		{exact128(0), "0"},
		{exact128(0x1p-59), "1.734723475976807094411924481391906737411209404266863396438627452099126993751360531E-18"},
		{exact128(0.25), "0.247466461547263452944781549788359289253766903098567696469117357944365179443666365"},
		{exact128(0.5), "0.4812118250596034474977589134243684231351843343856605196610181688401638676082217744"},
		{exact128(1), "0.8813735870195430252326093249797923090281603282616354107532956086533771842220260878"},
		{exact128(21), "3.738236030261542702926345171286353186644971465768736202615459010981959402821114935"},
		{exact128(0x1p59), "41.58883083359671856503392728749059408528232444614157925234079195342585455113665898"},

		{exact128(-0), "-0"},
		{exact128(-0.25), "-0.247466461547263452944781549788359289253766903098567696469117357944365179443666365"},
		{exact128(-0.5), "-0.4812118250596034474977589134243684231351843343856605196610181688401638676082217744"},
		{exact128(-1), "-0.8813735870195430252326093249797923090281603282616354107532956086533771842220260878"},
		{exact128(-21), "-3.738236030261542702926345171286353186644971465768736202615459010981959402821114935"},
	}

	for _, tt := range tests {
		got := tt.x.Asinh()
		if !close128(got, tt.want) {
			t.Errorf("Asinh(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}

	strictTests := []struct {
		x    Float128
		want Float128
	}{
		{exact128(0), exact128(0)},
		{exact128(math.Copysign(0, -1)), exact128(math.Copysign(0, -1))},

		// special cases
		{exact128(math.Inf(1)), exact128(math.Inf(1))},
		{exact128(math.Inf(-1)), exact128(math.Inf(-1))},
		{exact128(math.NaN()), exact128(math.NaN())},

		// tiny values: asinh(x) = x - x**3/6 + ... rounds to x
		{Float128{0x0000_0000_0000_0000, 0x0000_0000_0000_0001}, Float128{0x0000_0000_0000_0000, 0x0000_0000_0000_0001}},
		{exact128(-0x1p-16382), exact128(-0x1p-16382)},
		{exact128(0x1p-57), exact128(0x1p-57)},
		{Float128{0x3fc6_ffff_ffff_ffff, 0xffff_ffff_ffff_ffff}, Float128{0x3fc6_ffff_ffff_ffff, 0xffff_ffff_ffff_ffff}}, // 2**-56 - 2**-169: x**3/6 = 0.33 half ulp
		{exact128(0x1p-56), exact128(0x1p-56)},                                                                           // x**3/6 = 0.33 half ulp
		{exact128(-0x1p-56), exact128(-0x1p-56)},

		// the largest finite value: log(2x) is computed without overflow
		{Float128{0x7ffe_ffff_ffff_ffff, 0xffff_ffff_ffff_ffff}, Float128{0x400c_62e9_bb80_635d, 0x81d3_6125_b64d_a4a6}},
		{Float128{0xfffe_ffff_ffff_ffff, 0xffff_ffff_ffff_ffff}, Float128{0xc00c_62e9_bb80_635d, 0x81d3_6125_b64d_a4a6}},
	}

	for _, tt := range strictTests {
		got := tt.x.Asinh()
		if !eq128(got, tt.want) {
			t.Errorf("Asinh(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}
}

