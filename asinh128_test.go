// TestFloat128_AcoshFloat256 compares Acosh with the result calculated in Float256 and rounded to Float128.
// The error of the Float256 result is about 2**-130 times smaller than the ulp of Float128,
// so they must be the same except for extremely rare cases.
func TestFloat128_AcoshFloat256(t *testing.T) {
	t.Parallel()
	rnd := rand.New(rand.NewPCG(1, 2))
	one := Float256(uvone256)
	for i := range 20000 {
		var exp int
		switch i % 4 {
		case 0:
			exp = rnd.IntN(16000)
		case 1:
			exp = rnd.IntN(4)
		default:
			exp = rnd.IntN(30) + 55*(i/4%2) // around 1 and 2**60
		}
		x := Float128{rnd.Uint64(), rnd.Uint64()}
		x[0] = x[0]&0x0000_ffff_ffff_ffff | uint64(exp+16383)<<48
		if i%8 == 0 {
			x = Float128{0x3fff_0000_0000_0000, x[1] & 0xffff} // close to 1
		}
		if x == Float128(uvone128) {
			continue
		}

		got := x.Acosh()
		y := x.Float256()
		want := y.Add(y.Mul(y).Sub(one).Sqrt()).Log().Float128()
		if !eq128(got, want) {
			t.Errorf("Acosh(%v) = %v; want %v", x, got, want)
		}
	}
}

