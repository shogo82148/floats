// TestFloat128_AsinhFloat256 compares Asinh with the result calculated in Float256 and rounded to Float128.
// The error of the Float256 result is about 2**-130 times smaller than the ulp of Float128,
// so they must be the same except for extremely rare cases.
func TestFloat128_AsinhFloat256(t *testing.T) {
	t.Parallel()
	rnd := rand.New(rand.NewPCG(1, 2))
	one := Float256(uvone256)
	for i := range 20000 {
		var exp int
		switch i % 4 {
		case 0:
			exp = rnd.IntN(16000) - 8000
		case 1:
			exp = rnd.IntN(130) - 70
		default:
			exp = rnd.IntN(30) - 5 + 55*(i/4%2) // around 1 and 2**60
		}
		x := Float128{rnd.Uint64(), rnd.Uint64()}
		x[0] = x[0]&^(0x7fff<<48) | uint64(exp+16383)<<48

		got := x.Asinh()
		y := x.Float256()
		abs := y
		if x.Signbit() {
			abs = y.Neg()
		}
		want := abs.Add(abs.Mul(abs).Add(one).Sqrt()).Log().Float128()
		if exp < -56 {
			want = abs.Float128() // log(1+x) loses the precision. asinh(x) rounds to x.
		}
		if x.Signbit() {
			want = want.Neg()
		}
		if !eq128(got, want) {
			t.Errorf("Asinh(%v) = %v; want %v", x, got, want)
		}
	}
}

