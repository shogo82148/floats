func TestFloat256_Exp(t *testing.T) {
	t.Parallel()
	tests := []struct {
		x    Float256
		want string
	}{
		{exact256(-1), "0.3678794411714423215955237701614608674458111310317678345078368016974614957448998033571472743459196437466273252768439952082469757928"},
		{exact256(0), "1"},
		{exact256(1), "2.718281828459045235360287471352662497757247093699959574966967627724076630353547594571382178525166427427466391932003059921817413597"},
		{exact256(2), "7.389056098930650227230427460575007813180315570551847324087127822522573796079057763384312485079121794773753161265478866123884603693"},
		{exact256(3), "20.08553692318766774092852965458171789698790783855415014437893422969884587809197373120449716025301770215360761585194900288181101248"},
		{exact256(4), "54.59815003314423907811026120286087840279073703861406872582659395855366209993586948167698056194473414278411544577108742781175710394"},
	}

	for _, tt := range tests {
		got := tt.x.Exp()
		if !close256(got, tt.want) {
			t.Errorf("Exp(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}

	strictTests := []struct {
		x    Float256
		want Float256
	}{
		{exact256(0), exact256(1)},
		{exact256(math.Copysign(0, -1)), exact256(1)},

		// tiny values
		{Float256(uvone256).Ldexp(-239), exact256(1)},
		{Float256(uvone256).Ldexp(-239).Neg(), exact256(1)},
		{Float256(uvone256).Ldexp(-238), exact256(1)},
		{Float256(uvone256).Ldexp(-238).Neg(), exact256(1)},
		{Float256(uvone256).Ldexp(-237), Float256{0x3ffff00000000000, 0x0000000000000000, 0x0000000000000000, 0x0000000000000001}},
		{Float256(uvone256).Ldexp(-237).Neg(), Float256{0x3fffefffffffffff, 0xffffffffffffffff, 0xffffffffffffffff, 0xffffffffffffffff}},

		// overflow and underflow
		{exact256(181705), exact256(math.Inf(1))},
		{exact256(-181868), exact256(0)},
		{exact256(-181864), Float256{0, 0, 0, 0xd}},

		// special cases
		{exact256(math.Inf(1)), exact256(math.Inf(1))},
		{exact256(math.Inf(-1)), exact256(0)},
		{exact256(math.NaN()), exact256(math.NaN())},
	}

	for _, tt := range strictTests {
		got := tt.x.Exp()
		if !eq256(got, tt.want) {
			t.Errorf("Exp(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}
}

// TestFloat256_ExpAccuracy checks that the error of Exp is less than 1 ulp,
// and that almost all results are correctly rounded.
// The test data is generated by scripts/gen_exp_testdata.py.
func TestFloat256_ExpAccuracy(t *testing.T) {
	t.Parallel()
	testFloat256ExpAccuracy(t, "testdata/exp256.txt", "Exp", Float256.Exp)
}

