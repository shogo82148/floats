package floats

import (
	"math"
	"testing"
)

func TestFloat128_Jn(t *testing.T) {
	tests := []struct {
		n    int
		x    Float128
		want string
	}{
		{2, exact128(0.001), "0.0000001249999895833336640583308018882249650571491329274374792279965983335086"},
		{2, exact128(1), "0.1149034849319004804696468813351666053454703142302052604119687944409975"},
		{2, exact128(5), "0.04656511627775221553230328431069105796679039415888752151606601018222648"},
		{2, exact128(-5), "0.04656511627775221553230328431069105796679039415888752151606601018222648"},
		{-2, exact128(5), "0.04656511627775221553230328431069105796679039415888752151606601018222648"},
		{-2, exact128(-5), "0.04656511627775221553230328431069105796679039415888752151606601018222648"},
		{3, exact128(10), "0.05837937930518681234293547841034095629006899138151995639462218066356433"},
		{5, exact128(50), "-0.08140024769656963964397403792822206599602590829221977217887521371358348"},
		{10, exact128(100), "-0.05473217693547201474191745626593040825885930317558450100841066036381263"},

		// straddling the Miller / asymptotic crossover, x = max(500, 2*n**2)
		{2, exact128(499), "0.009730960400270855676120424270087344463490341775139810770572043303931247"},
		{2, exact128(500), "0.0341424473346134874365029288309224263497586579792626731749804598659607"},
		{2, exact128(500.1), "0.03500367081307590629076917020092519942904854824969269839045352898419558"},
		{50, exact128(4999), "0.0110805854692770522286542226238775062258591559024698147513158986623192"},
		{50, exact128(5000), "0.004186848572503984267649295971895728556174186142053175116590576521576791"},
		{50, exact128(5001), "-0.006554141755630365362738528670972784299404404335469941055626176966379943"},
		{100, exact128(19999), "0.003443950776193479173640683547073093690996547950246744772079544686622488"},
		{100, exact128(20000), "0.005621194614688300437882600238664226250197274916066365376984137357974333"},

		// deep Miller descent: large n and x both push the margin up
		{1000, exact128(1999999), "-0.0003546401689032456577508073261068959310357713979785152917676445639397273"},
		{1000, exact128(2000001), "0.0005465766019850108305743648765080154142332715592181673570781290658078364"},
	}

	for _, tt := range tests {
		got := tt.x.Jn(tt.n)
		if !close128(got, tt.want) {
			t.Errorf("Jn(%d, %v) = %v; want %v", tt.n, tt.x, got, tt.want)
		}
	}

	strictTests := []struct {
		n    int
		x    Float128
		want Float128
	}{
		{2, exact128(0), exact128(0)},
		{2, exact128(math.Inf(1)), exact128(0)},
		{2, exact128(math.Inf(-1)), exact128(0)},
		{2, exact128(math.NaN()), exact128(math.NaN())},
	}

	for _, tt := range strictTests {
		got := tt.x.Jn(tt.n)
		if !eq128(got, tt.want) {
			t.Errorf("Jn(%d, %v) = %v; want %v", tt.n, tt.x, got, tt.want)
		}
	}
}
