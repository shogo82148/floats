package floats

// Gamma returns the Gamma function of a.
//
// Special cases are:
//
//	+Inf.Gamma() = +Inf
//	+0.Gamma() = +Inf
//	-0.Gamma() = -Inf
//	x.Gamma() = NaN for integer x < 0
//	-Inf.Gamma() = NaN
//	NaN.Gamma() = NaN
func (a Float256) Gamma() Float256 {
	var (
		// Zero is 0
		Zero = Float256{}

		// Half is 0.5
		Half = Float256{
			0x3fff_e000_0000_0000, 0x0000_0000_0000_0000,
			0x0000_0000_0000_0000, 0x0000_0000_0000_0000,
		} // 0.5

		// One is 1
		One = Float256(uvone256)

		// Two is 2
		Two = Float256{
			0x4000_0000_0000_0000, 0x0000_0000_0000_0000,
			0x0000_0000_0000_0000, 0x0000_0000_0000_0000,
		} // 2.0

		// Three is 3
		Three = Float256{
			0x4000_0800_0000_0000, 0x0000_0000_0000_0000,
			0x0000_0000_0000_0000, 0x0000_0000_0000_0000,
		} // 3.0

		// Pi is π
		Pi = Float256{
			0x4000_0921_fb54_442d, 0x1846_9898_cc51_701b,
			0x839a_2520_49c1_114c, 0xf98e_8041_77d4_c762,
		} // 3.141592653589793238462643383279502884197169399375105820974944592307816406286209

		// StirlingThreshold is the threshold for using Stirling's approximation
		StirlingThreshold = Float256{
			0x4000_62c0_0000_0000, 0x0000_0000_0000_0000,
			0x0000_0000_0000_0000, 0x0000_0000_0000_0000,
		} // 150
	)

	// special cases
	switch {
	case isNegInt256(a) || a.IsInf(-1) || a.IsNaN():
		return NewFloat256NaN()
	case a.IsInf(1):
		return NewFloat256Inf(1)
	case a.IsZero():
		return NewFloat256Inf(1).Copysign(a)
	}

	q := a.Abs()
	p := q.Floor()
	if q.Ge(StirlingThreshold) {
		if !a.Signbit() {
			y1, y2 := stirling256(a)
			return y1.Mul(y2)
		}
		// Note: x is negative but (checked above) not a negative integer,
		// so x must be small enough to be in range for conversion to int256.
		// If |x| were >= 2²⁵⁶ it would have to be an integer.
		sign := !isOddInt256(p)
		z := q.Sub(p)
		if z.Gt(Half) {
			p = p.Add(One)
			z = q.Sub(p)
		}
		z = q.Mul(Pi.Mul(z).Sin())
		if z.IsZero() {
			return NewFloat256Inf(1)
		}
		sq1, sq2 := stirling256(q)
		absz := z.Abs()
		d := absz.Mul(sq1).Mul(sq2)
		if d.IsInf(0) {
			z = Pi.Quo(absz).Quo(sq1).Quo(sq2)
		} else {
			z = Pi.Quo(d)
		}
		if sign {
			z = z.Neg()
		}
		return z
	}

	// Reduce argument
	z := One
	for a.Ge(Three) {
		a = a.Sub(One)
		z = z.Mul(a)
	}
	for a.Lt(Zero) {
		z = z.Quo(a)
		a = a.Add(One)
	}
	for a.Lt(Two) {
		z = z.Quo(a)
		a = a.Add(One)
	}
	if a.Eq(Two) {
		return z
	}
	// Now 2 < a < 3.
	return z.Mul(gammaRational256(a))
}

func isNegInt256(x Float256) bool {
	if x.Lt(Float256{}) {
		_, xf := x.Modf()
		return xf.IsZero()
	}
	return false
}

