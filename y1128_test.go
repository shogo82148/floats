package floats

import (
	"math"
	"testing"
)

func TestFloat128_Y1(t *testing.T) {
	tests := []struct {
		x    Float128
		want string
	}{
		{exact128(0.001), "-636.62216723113941482210526019889109449409544720348295727316419518002998870723973"},
		{exact128(0.5), "-1.4714723926702430691885846353232974532410880554357483229559223834066940909523571"},
		{exact128(1), "-0.78121282130028871654715000004796482054990639071644460784383324612778439153856022"},
		{exact128(1.5), "-0.4123086269739112959528298206334453228850505655834628436270698874122235687588324"},

		// straddling the Temme-series / CF2 boundary (2)
		{exact128(1.999), "-0.10759642423945662741382468923511646100323827097496739232448893451722137126470797"},
		{exact128(2), "-0.10703243154093754688837077227747663668748089823505386052579455723131997749949067"},
		{exact128(2.001), "-0.1064686405140669759119122534417033621518722258153475188590516460709169391371785"},
		{exact128(2.5), "0.14591813796678579887875994053587757127608019654670099984510336876847982786986827"},
		{exact128(5), "0.14786314339122684480105067548803720537346521841047561330069765950868826592621711"},
		{exact128(10), "0.24901542420695388392328347466322280326041654306965846124694374102428875812470242"},
		{exact128(50), "-0.05679566856201476794181954923776336013440662539738030989643580941666844879626385"},
		{exact128(100), "-0.02037231200275979330470393266641455974201865568903699045979928263155680899959383"},
		{exact128(300), "0.033245548121310216055963850587394989576751478357111401256589654985634828686887215"},

		// straddling the CF2 / asymptotic boundary (500)
		{exact128(499), "0.0096275792217240845648119802250710531129132541740351093213462130714185195523992758"},
		{exact128(499.9), "0.032898442617060197700212562770795144489993903880327473607271878827055640705172525"},
		{exact128(500), "0.034111080629137135894793879829631993266090209028926378041899393682782025191675035"},
		{exact128(500.1), "0.03498268493599006204942003020865253161551979605360829140923441598292173076692348"},

		{exact128(1000), "-0.024784331292351778914862356097141290938631854864870528758349019940178780233621799"},
		{exact128(5000), "0.0066480726106254194163431538036595782932417383106815557422920866623726176493977783"},
	}

	for _, tt := range tests {
		got := tt.x.Y1()
		if !close128(got, tt.want) {
			t.Errorf("Y1(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}

	strictTests := []struct {
		x    Float128
		want Float128
	}{
		{exact128(0), exact128(math.Inf(-1))},
		{exact128(math.Copysign(0, -1)), exact128(math.Inf(-1))},
		{exact128(-1), exact128(math.NaN())},
		{exact128(math.Inf(1)), exact128(0)},
		{exact128(math.Inf(-1)), exact128(math.NaN())},
		{exact128(math.NaN()), exact128(math.NaN())},
	}

	for _, tt := range strictTests {
		got := tt.x.Y1()
		if !eq128(got, tt.want) {
			t.Errorf("Y1(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}
}
