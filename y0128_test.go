package floats

import (
	"math"
	"testing"
)

func TestFloat128_Y0(t *testing.T) {
	tests := []struct {
		x    Float128
		want string
	}{
		{exact128(0.001), "-4.4714166113759232557279276675494113171590730468609498648177305588485046592336927"},
		{exact128(0.5), "-0.44451873350670655714839847506833191037356512440151102041489117938823968793141729"},
		{exact128(1), "0.088256964215676957982926766023515162827817523090675546711043847611999789323513371"},
		{exact128(1.5), "0.38244892379775884395506855497808986236771000924182464517797513014755039974558862"},

		// straddling the Temme-series / CF2 boundary (2)
		{exact128(1.999), "0.51026835823865447557070292643556832778336382674848124422971594946785730809487083"},
		{exact128(2), "0.5103756726497451195966065927271578732681392270858461355718392719327313950418218"},
		{exact128(2.001), "0.5104824231689602061977832443854258241607918669049689082643820533654243723593463"},
		{exact128(2.5), "0.49807035961523188782747235036208980611506253265681530429974629407406321557566996"},
		{exact128(5), "-0.30851762524903378007364898421204661138634706162734404379585141589825791564288085"},
		{exact128(10), "0.055671167283599391424459877410190048145128114516905044082297913621922654163521798"},
		{exact128(50), "-0.098064995470077079029211453440370432007912776033783935263768598329777276716501615"},
		{exact128(100), "-0.077244313365083152254228221367198770505698983656635654771942777607654157501137232"},
		{exact128(300), "-0.031831889730003398014844175649005686398193181662568730769387989383460156847584391"},

		// straddling the CF2 / asymptotic boundary (500)
		{exact128(499), "0.03440585598313211012633720827425837088075221477421013858720444451602804906741561"},
		{exact128(499.9), "0.013859981772939215800697423949409403750459421446685020361049043035613807615476519"},
		{exact128(500), "0.010506708739831374099740660626553125825873868927222316347004348599031887576749718"},
		{exact128(500.1), "0.0070491372301601888198967329629044582417273374044759454317320271638157266394728577"},

		{exact128(1000), "0.0047159179776228133997732614656652550098590048968019771852800026829151397602999922"},
		{exact128(5000), "-0.0091167407696439626280591900810422020519599412680762774672728450467982917315632253"},
	}

	for _, tt := range tests {
		got := tt.x.Y0()
		if !close128(got, tt.want) {
			t.Errorf("Y0(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}

	strictTests := []struct {
		x    Float128
		want Float128
	}{
		{exact128(0), exact128(math.Inf(-1))},
		{exact128(math.Copysign(0, -1)), exact128(math.Inf(-1))},
		{exact128(-1), exact128(math.NaN())},
		{exact128(math.Inf(1)), exact128(0)},
		{exact128(math.Inf(-1)), exact128(math.NaN())},
		{exact128(math.NaN()), exact128(math.NaN())},
	}

	for _, tt := range strictTests {
		got := tt.x.Y0()
		if !eq128(got, tt.want) {
			t.Errorf("Y0(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}
}
