package floats

import (
	"math"
	"testing"
)

func TestFloat256_J1(t *testing.T) {
	tests := []struct {
		x    Float256
		want string
	}{
		{exact256(0.001), "0.00049999993750000261457494936592841528203228976565700992043863146797429028"},
		{exact256(0.5), "0.242268457674873886383954576141531640800628654437959753506925305893359847"},
		{exact256(1), "0.440050585744933515959682203718914913127372301992765251136758171780138225"},
		{exact256(-1), "-0.440050585744933515959682203718914913127372301992765251136758171780138225"},
		{exact256(2), "0.576724807756873387202448242269137086920302689719675440121139020764087115"},
		{exact256(5), "-0.327579137591465222037734321910169132760849904624054018686480645064875312"},
		{exact256(10), "0.043472746168861436669748768025859288306272867118594208135914322600980236"},
		{exact256(50), "-0.097511828125175137661458953873701614040488318984878589279591287505368667"},
		{exact256(100), "-0.0771453520141121580326854949272344702116116670992429716069733930414853266"},
		{exact256(300), "-0.0318874313774999503140012712809410452817558804164747789599852435742732282"},

		// straddling the Miller / asymptotic crossover (500)
		{exact256(499), "0.0343962609403376375013217977783762990698171691826451670912821209206872426"},
		{exact256(499.9), "0.0138270975969072804175160482437803078310825143975429064423488849374444767"},
		{exact256(500), "0.0104726134703722928444670947569670545789666118947006730943600296560324346"},
		{exact256(500.1), "0.00701417216224213662700209842481888748700533248877872777195229702545020862"},
		{exact256(501), "-0.0230220559956706164977688654091508662115306801466935094900624347032704887"},

		{exact256(1000), "0.00472831190708952391757607190121691628541802420205963686871972153612986853"},
		{exact256(5000), "-0.0091174057136461594787004021181064716449211207914203445748004415498172043"},
		{exact256(50000), "-0.00247764187086755263166446695903935491718859550100701532611809303705305039"},
	}

	for _, tt := range tests {
		got := tt.x.J1()
		if !close256(got, tt.want) {
			t.Errorf("J1(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}

	strictTests := []struct {
		x    Float256
		want Float256
	}{
		{exact256(0), exact256(0)},
		{exact256(math.Copysign(0, -1)), exact256(math.Copysign(0, -1))},
		{exact256(math.Inf(1)), exact256(0)},
		{exact256(math.Inf(-1)), exact256(0)},
		{exact256(math.NaN()), exact256(math.NaN())},
	}

	for _, tt := range strictTests {
		got := tt.x.J1()
		if !eq256(got, tt.want) {
			t.Errorf("J1(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}
}
