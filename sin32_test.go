// TestFloat32_SinCosTanAccuracy checks that the error of Sin, Cos, Sincos, and Tan is less than 1 ulp,
// and that almost all results are correctly rounded.
// The test data is generated by scripts/gen_sin_testdata.py.
func TestFloat32_SinCosTanAccuracy(t *testing.T) {
	t.Parallel()
	total, misrounded := testFloat32SinCosTan(t, "testdata/sin32.txt")
	if misrounded*100 > total {
		t.Errorf("%d of %d results are not correctly rounded; want at most 1%%", misrounded, total)
	}
}

// TestFloat32_SinCosTanHardCases checks that the error of Sin, Cos, Sincos, and Tan is less than 1 ulp
// on the inputs whose results are very close to the midpoint of two adjacent Float32 values.
// They may not be correctly rounded.
// The test data is generated by scripts/gen_sin_testdata.py.
func TestFloat32_SinCosTanHardCases(t *testing.T) {
	t.Parallel()
	testFloat32SinCosTan(t, "testdata/sin32_hard.txt")
}

func testFloat32SinCosTan(t *testing.T, name string) (total, misrounded int) {
	t.Helper()
	f, err := os.Open(name)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()

	parse := func(s string) Float32 {
		v, err := strconv.ParseUint(s, 16, 32)
		if err != nil {
			t.Fatal(err)
		}
		return NewFloat32FromBits(uint32(v))
	}

	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		x, wantSin, wantCos, wantTan := parse(fields[0]), parse(fields[1]), parse(fields[2]), parse(fields[3])

		sin, cos := x.Sincos()
		tan := x.Tan()
		total += 3
		if !eq32(sin, wantSin) {
			misrounded++
		}
		if !eq32(cos, wantCos) {
			misrounded++
		}
		if !eq32(tan, wantTan) {
			misrounded++
		}
		if !within1ulp32(sin, wantSin) {
			t.Errorf("Sincos(%v) sin = %v; want %v", x, sin, wantSin)
		}
		if !within1ulp32(cos, wantCos) {
			t.Errorf("Sincos(%v) cos = %v; want %v", x, cos, wantCos)
		}
		if !within1ulp32(tan, wantTan) {
			t.Errorf("Tan(%v) = %v; want %v", x, tan, wantTan)
		}
		if got := x.Sin(); !eq32(got, sin) {
			t.Errorf("Sin(%v) = %v; want %v", x, got, sin)
		}
		if got := x.Cos(); !eq32(got, cos) {
			t.Errorf("Cos(%v) = %v; want %v", x, got, cos)
		}
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	t.Logf("%d of %d results are not correctly rounded", misrounded, total)
	return
}

// TestFloat32_SinCosTanRandom compares Sin, Cos, Sincos, and Tan with math.Sin, math.Cos, and math.Tan on random inputs.
// math.Sin, math.Cos, and math.Tan rounded to float32 are correctly rounded except for rare cases,
// so the results should almost always match.
func TestFloat32_SinCosTanRandom(t *testing.T) {
	t.Parallel()
	r := rand.New(rand.NewPCG(1, 2))
	gens := []struct {
		name string
		gen  func() Float32
	}{
		{"bits", func() Float32 { return NewFloat32FromBits(r.Uint32()) }},
		{"uniform", func() Float32 { return NewFloat32(r.Float64()*16 - 8) }},
		{"exponent", func() Float32 {
			// uniformly distributed exponent in [-20, 127]
			return NewFloat32FromBits(r.Uint32()&(signMask32|fracMask32) | uint32(r.IntN(148)+bias32-20)<<shift32)
		}},
	}
	for _, g := range gens {
		var mismatch int
		for range 300000 {
			x := g.gen()
			if x.IsNaN() || x.IsInf(0) {
				continue
			}
			wantSin := NewFloat32(math.Sin(float64(x)))
			wantCos := NewFloat32(math.Cos(float64(x)))
			sin, cos := x.Sincos()
			if !within1ulp32(sin, wantSin) {
				t.Fatalf("Sincos(%v) sin = %v; want %v", x, sin, wantSin)
			}
			if !within1ulp32(cos, wantCos) {
				t.Fatalf("Sincos(%v) cos = %v; want %v", x, cos, wantCos)
			}
			if !eq32(sin, wantSin) {
				mismatch++
			}
			if !eq32(cos, wantCos) {
				mismatch++
			}
			if got := x.Sin(); !eq32(got, sin) {
				t.Fatalf("Sin(%v) = %v; want %v", x, got, sin)
			}
			if got := x.Cos(); !eq32(got, cos) {
				t.Fatalf("Cos(%v) = %v; want %v", x, got, cos)
			}

			wantTan := NewFloat32(math.Tan(float64(x)))
			tan := x.Tan()
			if !within1ulp32(tan, wantTan) {
				t.Fatalf("Tan(%v) = %v; want %v", x, tan, wantTan)
			}
			if !eq32(tan, wantTan) {
				mismatch++
			}
		}
		// Checking all Float32 values, about 200 of 3*2**32 results are different.
		if mismatch > 3 {
			t.Errorf("%s: %d results are different from math.Sin, math.Cos, and math.Tan", g.name, mismatch)
		}
	}
}

// within1ulp32 reports whether got is within 1 ulp of want.
func within1ulp32(got, want Float32) bool {
	inf := NewFloat32Inf(1)
	return eq32(got, want) || eq32(got, want.Nextafter(inf)) || eq32(got, want.Nextafter(inf.Neg()))
}

