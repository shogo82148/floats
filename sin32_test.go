func TestFloat32_Sin(t *testing.T) {
	t.Parallel()
	tests := []struct {
		x    Float32
		want float64
	}{
		{exact32(-3), math.Sin(-3)},
		{exact32(-2), math.Sin(-2)},
		{exact32(-1), math.Sin(-1)},
		{exact32(1), math.Sin(1)},
		{exact32(2), math.Sin(2)},
		{exact32(3), math.Sin(3)},
		{exact32(0x1p28), math.Sin(0x1p28)},
	}

	for _, tt := range tests {
		got := tt.x.Sin()
		if !close32(got, tt.want) {
			t.Errorf("Sin(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}

	strictTests := []struct {
		x    Float32
		want Float32
	}{
		// special cases
		{exact32(0), exact32(0)},
		{exact32(math.Copysign(0, -1)), exact32(math.Copysign(0, -1))},
		{exact32(math.Inf(1)), exact32(math.NaN())},
		{exact32(math.Inf(-1)), exact32(math.NaN())},
		{exact32(math.NaN()), exact32(math.NaN())},

		// tiny arguments
		{NewFloat32FromBits(0x00000001), NewFloat32FromBits(0x00000001)},
		{NewFloat32FromBits(0x80000001), NewFloat32FromBits(0x80000001)},
		{NewFloat32FromBits(0x397fffff), NewFloat32FromBits(0x397fffff)},
	}
	for _, tt := range strictTests {
		got := tt.x.Sin()
		if !eq32(got, tt.want) {
			t.Errorf("Sin(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}
}

