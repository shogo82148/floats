package floats

import (
	"math"
	"testing"
)

func TestFloat128_J1(t *testing.T) {
	tests := []struct {
		x    Float128
		want string
	}{
		{exact128(0.001), "0.0004999999375000026145749493659284152820322897656570099204386"},
		{exact128(0.5), "0.2422684576748738863839545761415316408006286544379597535069253"},
		{exact128(1), "0.4400505857449335159596822037189149131273723019927652511367581"},
		{exact128(-1), "-0.4400505857449335159596822037189149131273723019927652511367581"},
		{exact128(2), "0.5767248077568733872024482422691370869203026897196754401211390"},
		{exact128(5), "-0.3275791375914652220377343219101691327608499046240540186864806"},
		{exact128(10), "0.04347274616886143666974876802585928830627286711859420813591432"},
		{exact128(50), "-0.09751182812517513766145895387370161404048831898487858927959129"},
		{exact128(100), "-0.07714535201411215803268549492723447021161166709924297160697339"},
		{exact128(300), "-0.03188743137749995031400127128094104528175588041647477895998524"},

		// straddling the Miller / asymptotic crossover (500)
		{exact128(499), "0.03439626094033763750132179777837629906981716918264516709128212"},
		{exact128(499.9), "0.01382709759690728041751604824378030783108251439754290644234888"},
		{exact128(500), "0.01047261347037229284446709475696705457896661189470067309436003"},
		{exact128(500.1), "0.007014172162242136627002098424818887487005332488778727771952297"},
		{exact128(501), "-0.02302205599567061649776886540915086621153068014669350949006243"},

		{exact128(1000), "0.004728311907089523917576071901216916285418024202059636868719722"},
		{exact128(5000), "-0.009117405713646159478700402118106471644921120791420344574800442"},
		{exact128(50000), "-0.002477641870867552631664466959039354917188595501007015326118093"},
	}

	for _, tt := range tests {
		got := tt.x.J1()
		if !close128(got, tt.want) {
			t.Errorf("J1(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}

	strictTests := []struct {
		x    Float128
		want Float128
	}{
		{exact128(0), exact128(0)},
		{exact128(math.Copysign(0, -1)), exact128(math.Copysign(0, -1))},
		{exact128(math.Inf(1)), exact128(0)},
		{exact128(math.Inf(-1)), exact128(0)},
		{exact128(math.NaN()), exact128(math.NaN())},
	}

	for _, tt := range strictTests {
		got := tt.x.J1()
		if !eq128(got, tt.want) {
			t.Errorf("J1(%v) = %v; want %v", tt.x, got, tt.want)
		}
	}
}
